"""Write results/REPORT.md from the JSON results (numbers are never typed in by hand)."""

from __future__ import annotations

import json
from typing import Any

from common import RESULTS


def load(name: str) -> dict[str, Any] | None:
    path = RESULTS / f"{name}.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def table(header: list[str], rows: list[list[Any]]) -> str:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join("—" if v is None else str(v) for v in r) + " |" for r in rows]
    return "\n".join(out)


def main() -> None:
    parts = [
        "# PrescripTrace evaluation results",
        "",
        "Generated by `evaluation/report.py` from `evaluation/results/*.json`. How each number "
        "was produced, and its limits, is in [METHODOLOGY.md](../METHODOLOGY.md).",
        "",
    ]

    n = load("normalisation")
    if n:
        parts += [
            f"## Name recognition ({n['run_at']})",
            "",
            f"{n['cases']} cases ({n['hand_written']} hand-written, {n['generated_typos']} "
            f"generated typos); thresholds {n['thresholds']}.",
            "",
            table(
                ["Metric", "Value"],
                [
                    ["Top-1 accuracy (medicine cases)", f"{n['top1_pct']}%"],
                    ["Top-3 accuracy", f"{n['top3_pct']}%"],
                    ["Auto-accepted (no question asked)", f"{n['auto_accepted_pct']}%"],
                    ["**Wrong auto-accepts** (safety)", n["wrong_auto_accept"]],
                    [
                        "Non-medicine lines auto-accepted",
                        f"{n['non_medicine_resolved']} of {n['non_medicine_cases']}",
                    ],
                ],
            ),
            "",
            table(
                ["Category", "Cases", "Top-1 %", "Top-3 %", "Outcomes"],
                [
                    [
                        k,
                        v["cases"],
                        v["top1_pct"],
                        v["top3_pct"],
                        ", ".join(f"{a} {b}" for a, b in v["outcomes"].items()),
                    ]
                    for k, v in n["by_category"].items()
                ],
            ),
            "",
            "Not found: " + "; ".join(f"`{r['text']}`" for r in n["not_found"]) + ".",
            "",
            "Not in our vocabulary (coverage gap): " + "; ".join(n["not_in_vocabulary"]) + ".",
            "",
        ]

    i = load("interactions")
    if i:
        tiers = i["recall_by_reference_tier"]
        parts += [
            f"## Interactions vs CRESCENDDI ({i['run_at']})",
            "",
            f"{i['positive_pairs_mapped']} interacting pairs and {i['negative_pairs_mapped']} "
            f"negative-control pairs mapped to our ingredients "
            f"({i['drug_names_unmapped']} drug names could not be mapped exactly).",
            "",
            table(
                [
                    "Reference severity (BNF/ANSM/Micromedex)",
                    "Pairs",
                    "Any warning %",
                    "Worth checking or higher %",
                    "Needs attention %",
                ],
                [
                    [
                        t,
                        v["pairs"],
                        v["flagged_pct"],
                        v["worth_checking_or_higher_pct"],
                        v["needs_attention_pct"],
                    ]
                    for t, v in tiers.items()
                    if v["pairs"]
                ],
            ),
            "",
            table(
                ["On negative controls", "Value"],
                [
                    [
                        "Any finding (incl. ungraded DDInter listings, shown collapsed)",
                        f"{i['false_alarm_any_pct']}%",
                    ],
                    [
                        "Worth checking or higher",
                        f"{i['false_alarm_worth_checking_or_higher_pct']}%",
                    ],
                    [
                        "Needs attention (major/contraindicated)",
                        f"{i['false_alarm_needs_attention_pct']}%",
                    ],
                    [
                        "Our severity on flagged negatives",
                        ", ".join(
                            f"{k} {v}" for k, v in i["negative_flagged_by_our_severity"].items()
                        ),
                    ],
                ],
            ),
            "",
            f"Precision on the labelled set: {i['precision_any_pct']}% (any finding), "
            f"{i['precision_needs_attention_pct']}% (needs attention).",
            "",
            "Reference severity (rows) against our severity (columns):",
            "",
            table(
                ["Reference", *next(iter(i["confusion_reference_tier_vs_our_severity"].values()))],
                [
                    [t, *row.values()]
                    for t, row in i["confusion_reference_tier_vs_our_severity"].items()
                    if sum(row.values())
                ],
            ),
            "",
            f"Serious reference pairs with no warning: {i['missed_serious_count']} "
            f"(e.g. {', '.join(i['missed_serious_examples'][:10])}).",
            "",
        ]

    o = load("ocr")
    if o:
        parts += [
            f"## Prescription reading ({o['run_at']})",
            "",
            f"Engine: {o['engine']}; {o['pages_per_variant']} pages per variant. "
            "**Handwriting-style = handwriting fonts, not real handwriting (upper bound).**",
            "",
            table(
                [
                    "Variant",
                    "Medicine lines",
                    "Found (auto or in top 3) %",
                    "Added in one tap %",
                    "Wrong auto-accepts",
                    "Median CER",
                    "Extra lines offered",
                    "p50 page ms",
                ],
                [
                    [
                        k,
                        v["medicine_lines"],
                        v["found_correct_pct"],
                        v["auto_correct_pct"],
                        v["wrong_auto_accept"],
                        v["median_cer"],
                        v["false_medicine_lines"],
                        v["page_time"]["p50_ms"],
                    ]
                    for k, v in o["by_variant"].items()
                ],
            ),
            "",
            table(
                ["Group", "Lines", "Found %", "One tap %", "Wrong auto-accepts", "Missed %"],
                [
                    [
                        g,
                        o[g]["medicine_lines"],
                        o[g]["found_correct_pct"],
                        o[g]["auto_correct_pct"],
                        o[g]["wrong_auto_accept"],
                        o[g]["missed_pct"],
                    ]
                    for g in ("printed", "handwriting_style")
                ],
            ),
            "",
        ]

    lat = load("latency")
    if lat:
        parts += [
            f"## Latency ({lat['run_at']})",
            "",
            lat["method"] + ".",
            "",
            table(
                ["Call", "n", "p50 ms", "p95 ms", "max ms", "Response (gzip)"],
                [
                    [
                        k,
                        v["n"],
                        v["p50_ms"],
                        v["p95_ms"],
                        v["max_ms"],
                        f"{lat['response_bytes_gzipped'].get(k, 0) / 1000:.1f} kB",
                    ]
                    for k, v in lat["latency"].items()
                    if isinstance(v, dict)
                ],
            ),
            "",
            f"Offline pack: first build {lat['latency']['offline_pack_first_build_ms']} ms "
            f"(then cached), download "
            f"{lat['response_bytes_gzipped']['offline_pack'] / 1e6:.2f} MB.",
            "",
        ]

    versions = (n or i or o or lat or {}).get("dataset_versions", {})
    parts += [
        "## Data versions",
        "",
        ", ".join(f"{k} {v}" for k, v in sorted(versions.items())),
        "",
    ]
    (RESULTS / "REPORT.md").write_text("\n".join(parts), encoding="utf-8")
    print("written", RESULTS / "REPORT.md")


if __name__ == "__main__":
    main()
